function hit(
  userId: string,
  schemeCode: string,
  batchId: string,
  profileVersionId: string,
  profileVersionLabel: string,
  layerName: string,
  hitAt: string,
) {
  const user = USERS.find((item) => item.id === userId)
  return {
    userId,
    userName: user ? user.name : userId,
    schemeCode,
    batchId,
    profileVersionId,
    profileVersionLabel,
    layerName,
    hitAt,
  }
}

